//! 动作执行失败。
//!
//! 只有一种失败值得区分出来：**输入不合法**（用户填的东西不对）与**内部错误**（不该发生）。
//! 前者要把原因说清楚（"不是合法的 Base64"），后者是 bug。
//!
//! ⚠️ 错误文案是**给人看的中文**，和 Go 一样。它不回给浏览器做 i18n —— 定时任务失败时
//! 这条文案进的是服务端日志和任务状态，收件人看不到。所以这里不像动作名那样只给 key。

use thiserror::Error;

#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum ActionError {
    /// 输入不符合这个动作的要求（Base64 坏了、hex 是奇数长度、JSON 解析不了……）。
    ///
    /// ⚠️ **不要**给这些错误配一个「返回原文本」的兜底：那会让用户以为动作生效了，
    /// 而链上后面的动作拿着没处理过的文本继续跑 —— 正是这个项目最怕的静默错误。
    #[error("{0}")]
    InvalidInput(String),

    /// 参数不对（缺必填项、没法解释的枚举值……）。
    #[error("{0}")]
    BadParams(String),

    /// 调用方给的 id 不在注册表里，或者在当前 feature 组合下不可用。
    ///
    /// ⚠️ 与「静默跳过」的区别就是这条存在的理由：定时任务是无人值守的，
    /// 静默跳过会让用户以为动作跑了，等到消息真的发进房间才发现 —— 那时已经过了几个小时。
    #[error("动作 {id:?} 不在可执行集合里（可用动作：{}）", .available.join(" / "))]
    UnknownAction {
        id: String,
        /// 当前这一版里可用的动作 id。失败信息里带上它，排查时不用再翻文档。
        available: Vec<String>,
    },
}
